const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  loadConfig: () => ipcRenderer.invoke('load-config'),
  saveConfig: (data, conflictBases) => ipcRenderer.invoke('save-config', data, conflictBases),
  importSyllabus: () => ipcRenderer.invoke('import-syllabus'),
  setOpacity: (v) => ipcRenderer.send('set-opacity', v),
  setAlwaysOnTop: (f) => ipcRenderer.send('set-always-on-top', f),
  close: () => ipcRenderer.send('close-app'),
  minimize: () => ipcRenderer.send('minimize-app'),
  notify: (title, body) => ipcRenderer.send('notify', { title, body }),
  lmsLogin: () => ipcRenderer.invoke('lms-login'),
  lmsStatus: () => ipcRenderer.invoke('lms-status'),
  lmsRefresh: () => ipcRenderer.invoke('lms-refresh'),
  lmsOpen: (url) => ipcRenderer.send('lms-open', url),
  lmsDump: () => ipcRenderer.invoke('lms-dump'),
  setMini: (on) => ipcRenderer.send('set-mini', on),
  getAutoStart: () => ipcRenderer.invoke('get-auto-start'),
  setAutoStart: (on) => ipcRenderer.invoke('set-auto-start', on),
  onSubmissionClosed: (cb) => ipcRenderer.on('lms-submission-closed', () => cb()),
  lmsDownload: (items) => ipcRenderer.invoke('lms-download', items),
  openStudeckFolder: (kind, course) => ipcRenderer.invoke('open-studeck-folder', { kind, course }),
  gitConnect: (repo, token) => ipcRenderer.invoke('git-connect', { repo, token }),
  gitSync: (resolution) => ipcRenderer.invoke('git-sync', resolution),
  onSyncStatus: cb => ipcRenderer.on('sync-status', (_e, status) => cb(status)),
  onRequestQuit: cb => ipcRenderer.on('request-quit', () => cb()),
  gitSyncStatus: () => ipcRenderer.invoke('git-sync-status'),
  gitDisconnect: () => ipcRenderer.invoke('git-disconnect'),
  serverSignup: (username, password, displayName, consent) => ipcRenderer.invoke('server-signup', { username, password, displayName, consent }),
  accountMe: () => ipcRenderer.invoke('account-me'),
  accountPassword: (current, next) => ipcRenderer.invoke('account-password', { current, next }),
  accountWithdraw: (password) => ipcRenderer.invoke('account-withdraw', { password }),
  accountGithubLink: (accessToken) => ipcRenderer.invoke('account-github-link', accessToken),
  accountGithubUnlink: () => ipcRenderer.invoke('account-github-unlink'),
  githubReset: (username, accessToken, newPassword) => ipcRenderer.invoke('github-reset', { username, accessToken, newPassword }),
  githubDeviceStart: () => ipcRenderer.invoke('github-device-start'),
  githubDevicePoll: (deviceCode) => ipcRenderer.invoke('github-device-poll', deviceCode),
  serverLogin: (username, password) => ipcRenderer.invoke('server-login', { username, password }),
  serverLogout: () => ipcRenderer.invoke('server-logout'),
  importProdData: () => ipcRenderer.invoke('import-prod-data'),
  serverRefreshMe: () => ipcRenderer.invoke('server-refresh-me'),
  communityCall: (method, path, body) => ipcRenderer.invoke('community-call', { method, path, body }),
  communitySocketInfo: () => ipcRenderer.invoke('community-socket-info'),
  communityUpload: (bytes) => ipcRenderer.invoke('community-upload', bytes),
  communityMedia: (sha) => ipcRenderer.invoke('community-media', sha),
  filesOverview: () => ipcRenderer.invoke('files-overview'),
  filesVersions: (p) => ipcRenderer.invoke('files-versions', p),
  filesRestore: (p) => ipcRenderer.invoke('files-restore', p),
  filesRevert: (p, vid) => ipcRenderer.invoke('files-revert', { path: p, vid }),
  adminUsers: () => ipcRenderer.invoke('admin-users'),
  adminAction: (id, action, role) => ipcRenderer.invoke('admin-action', { id, action, role }),
});
